-- Worth It user chat: global chat, friend DMs, group chats, moderation and media.
-- Run once in Supabase SQL Editor AFTER worth-it-social.sql and worth-it-profiles.sql.

create table if not exists public.worth_it_chat_conversations (
    id uuid primary key default gen_random_uuid(),
    conversation_type text not null check (conversation_type in ('global','direct','group')),
    title text,
    created_by uuid references auth.users(id) on delete set null,
    created_at timestamptz not null default now()
);
create unique index if not exists worth_it_chat_one_global_idx
    on public.worth_it_chat_conversations(conversation_type) where conversation_type = 'global';
insert into public.worth_it_chat_conversations(id, conversation_type, title)
values ('00000000-0000-4000-8000-000000000001', 'global', 'Global Chat')
on conflict (id) do nothing;

create table if not exists public.worth_it_chat_members (
    conversation_id uuid not null references public.worth_it_chat_conversations(id) on delete cascade,
    user_id uuid not null references auth.users(id) on delete cascade,
    joined_at timestamptz not null default now(),
    last_read_at timestamptz,
    primary key (conversation_id, user_id)
);
create index if not exists worth_it_chat_members_user_idx
    on public.worth_it_chat_members(user_id, joined_at desc);

create table if not exists public.worth_it_chat_notification_preferences (
    user_id uuid not null references auth.users(id) on delete cascade,
    chat_key text not null,
    notifications_enabled boolean not null default true,
    updated_at timestamptz not null default now(),
    primary key (user_id, chat_key),
    constraint worth_it_chat_notification_key_valid check (
        chat_key = 'global'
        or chat_key ~ '^direct:[1-9][0-9]*$'
        or chat_key ~ '^group:[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$'
    )
);

revoke all on public.worth_it_chat_notification_preferences from public, anon, authenticated;

create table if not exists public.worth_it_chat_messages (
    id bigint generated by default as identity primary key,
    conversation_id uuid not null references public.worth_it_chat_conversations(id) on delete cascade,
    sender_user_id uuid not null references auth.users(id) on delete cascade,
    body text not null default '',
    media_url text,
    media_type text check (media_type is null or media_type in ('image','gif')),
    filtered_reason text,
    created_at timestamptz not null default now(),
    constraint worth_it_chat_message_body_len check (char_length(body) <= 500),
    constraint worth_it_chat_message_not_empty check (char_length(btrim(body)) > 0 or media_url is not null)
);
create index if not exists worth_it_chat_messages_conversation_idx
    on public.worth_it_chat_messages(conversation_id, id desc);

