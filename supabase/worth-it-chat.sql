create or replace function public.get_worth_it_chat_friends()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare actor_id uuid := auth.uid(); result jsonb;
begin
    if actor_id is null then raise exception 'Authentication required'; end if;
    select coalesce(jsonb_agg(jsonb_build_object(
        'worth_it_id', p.worth_it_id,
        'username', p.username,
        'display_name', coalesce(p.display_name, p.username, 'Worth It member'),
        'avatar_url', p.avatar_url
    ) order by lower(coalesce(p.display_name, p.username, ''))), '[]'::jsonb)
    into result
    from public.worth_it_friends f
    join public.worth_it_profiles p on p.user_id =
        case when f.user_low_id = actor_id then f.user_high_id else f.user_low_id end
    where f.user_low_id = actor_id or f.user_high_id = actor_id;
    return result;
end; $$;

create or replace function public.get_worth_it_chat_conversations()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare actor_id uuid := auth.uid(); result jsonb;
begin
    if actor_id is null then raise exception 'Authentication required'; end if;
    select coalesce(jsonb_agg(jsonb_build_object(
        'id', c.id, 'type', c.conversation_type, 'title', c.title,
        'created_at', c.created_at,
        'members', (select coalesce(jsonb_agg(jsonb_build_object(
            'worth_it_id', p.worth_it_id, 'username', p.username,
            'display_name', coalesce(p.display_name,p.username,'Worth It member'),
            'avatar_url', p.avatar_url
        ) order by lower(coalesce(p.display_name,p.username,''))), '[]'::jsonb)
        from public.worth_it_chat_members cm
        join public.worth_it_profiles p on p.user_id = cm.user_id
        where cm.conversation_id = c.id and cm.user_id <> actor_id),
        'last_message', (select jsonb_build_object('body', m.body, 'created_at', m.created_at,
            'sender_user_id', m.sender_user_id, 'media_type', m.media_type)
            from public.worth_it_chat_messages m where m.conversation_id = c.id
            order by m.id desc limit 1),
        'unread_count', (select count(*) from public.worth_it_chat_messages m
            left join public.worth_it_chat_members mine on mine.conversation_id = c.id and mine.user_id = actor_id
            where m.conversation_id = c.id and m.sender_user_id <> actor_id
            and (mine.last_read_at is null or m.created_at > mine.last_read_at))
    ) order by coalesce((select max(m2.created_at) from public.worth_it_chat_messages m2 where m2.conversation_id=c.id), c.created_at) desc), '[]'::jsonb)
    into result
    from public.worth_it_chat_conversations c
    join public.worth_it_chat_members mine on mine.conversation_id = c.id and mine.user_id = actor_id
    where c.conversation_type in ('direct','group');
    return result;
end; $$;

create or replace function public.get_worth_it_chat_messages(p_conversation_id uuid default null, p_limit integer default 100)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
    actor_id uuid := auth.uid();
    target_id uuid := coalesce(p_conversation_id, '00000000-0000-4000-8000-000000000001'::uuid);
    target_type text;
    result jsonb;
begin
    if actor_id is null then raise exception 'Authentication required'; end if;
    select conversation_type into target_type from public.worth_it_chat_conversations where id=target_id;
    if target_type is null then return jsonb_build_object('success',false,'code','CHAT_NOT_FOUND'); end if;
    if target_type <> 'global' and not exists (
        select 1 from public.worth_it_chat_members where conversation_id=target_id and user_id=actor_id
    ) then return jsonb_build_object('success',false,'code','NOT_A_CHAT_MEMBER'); end if;

    select coalesce(jsonb_agg(row_data order by message_id), '[]'::jsonb) into result
    from (
        select m.id as message_id, jsonb_build_object(
            'id',m.id,'body',m.body,'media_url',m.media_url,'media_type',m.media_type,
            'filtered_reason',m.filtered_reason,'created_at',m.created_at,
            'sender_user_id',m.sender_user_id,'worth_it_id',p.worth_it_id,
            'username',p.username,'display_name',coalesce(p.display_name,p.username,'Worth It member'),
            'avatar_url',p.avatar_url
        ) as row_data
        from public.worth_it_chat_messages m
        join public.worth_it_profiles p on p.user_id=m.sender_user_id
        where m.conversation_id=target_id
        order by m.id desc limit greatest(1, least(coalesce(p_limit,100),100))
    ) q;
    insert into public.worth_it_chat_members(conversation_id,user_id,last_read_at)
    values(target_id,actor_id,now())
    on conflict (conversation_id,user_id) do update set last_read_at=excluded.last_read_at;
    return result;
end; $$;

create or replace function public.open_worth_it_friend_chat(target_worth_it_id bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare actor_id uuid := auth.uid(); target_user_id uuid; low_id uuid; high_id uuid; conversation uuid;
begin
    if actor_id is null then raise exception 'Authentication required'; end if;
    select user_id into target_user_id from public.worth_it_profiles where worth_it_id=target_worth_it_id;
    if target_user_id is null then return jsonb_build_object('success',false,'code','PROFILE_NOT_FOUND'); end if;
    if target_user_id=actor_id then return jsonb_build_object('success',false,'code','CANNOT_CHAT_SELF'); end if;
    if not exists(select 1 from public.worth_it_friends where
        (user_low_id=actor_id and user_high_id=target_user_id) or
        (user_low_id=target_user_id and user_high_id=actor_id)) then
        return jsonb_build_object('success',false,'code','FRIENDS_ONLY');
    end if;
    low_id:=least(actor_id,target_user_id); high_id:=greatest(actor_id,target_user_id);
    select c.id into conversation from public.worth_it_chat_conversations c
    join public.worth_it_chat_members a on a.conversation_id=c.id and a.user_id=low_id
    join public.worth_it_chat_members b on b.conversation_id=c.id and b.user_id=high_id
    where c.conversation_type='direct'
      and (select count(*) from public.worth_it_chat_members x where x.conversation_id=c.id)=2
    limit 1;
    if conversation is null then
        insert into public.worth_it_chat_conversations(conversation_type,created_by) values('direct',actor_id) returning id into conversation;
        insert into public.worth_it_chat_members(conversation_id,user_id) values(conversation,low_id),(conversation,high_id);
    end if;
    return jsonb_build_object('success',true,'conversation_id',conversation);
end; $$;

create or replace function public.create_worth_it_group_chat(p_title text, p_member_worth_it_ids bigint[])
returns jsonb language plpgsql security definer set search_path = public as $$
declare
    actor_id uuid := auth.uid(); conversation uuid; member_id bigint; member_user uuid;
    clean_title text := nullif(btrim(coalesce(p_title,'')),''); requested_count integer := 0;
begin
    if actor_id is null then raise exception 'Authentication required'; end if;
    if clean_title is null or char_length(clean_title)>60 then
        return jsonb_build_object('success',false,'code','INVALID_GROUP_TITLE');
    end if;
    requested_count := coalesce(cardinality(p_member_worth_it_ids),0);
    if requested_count < 2 or requested_count > 29 then
        return jsonb_build_object('success',false,'code','INVALID_GROUP_SIZE','max_members',30);
    end if;
    insert into public.worth_it_chat_conversations(conversation_type,title,created_by)
    values('group',clean_title,actor_id) returning id into conversation;
    insert into public.worth_it_chat_members(conversation_id,user_id) values(conversation,actor_id);
    foreach member_id in array p_member_worth_it_ids loop
        select user_id into member_user from public.worth_it_profiles where worth_it_id=member_id;
        if member_user is null or member_user=actor_id then
            raise exception 'Invalid group participant';
        end if;
        if not exists(select 1 from public.worth_it_friends where
            (user_low_id=actor_id and user_high_id=member_user) or
            (user_low_id=member_user and user_high_id=actor_id)) then
            raise exception 'Group participants must be your friends';
        end if;
        insert into public.worth_it_chat_members(conversation_id,user_id) values(conversation,member_user)
        on conflict do nothing;
    end loop;
    if (select count(*) from public.worth_it_chat_members where conversation_id=conversation)<3 then
        raise exception 'Choose at least two friends for a group chat';
    end if;
    return jsonb_build_object('success',true,'conversation_id',conversation);
end; $$;

create or replace function public.send_worth_it_chat_message(
    p_body text default '',
    p_conversation_id uuid default null,
    p_media_url text default null,
    p_media_type text default null
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
    actor_id uuid := auth.uid();
    target_id uuid := coalesce(p_conversation_id, '00000000-0000-4000-8000-000000000001'::uuid);
    target_type text;
    clean_body text := coalesce(p_body,'');
    masked_body text;
    filter_reason text := null;
    term_row record;
    message_id bigint;
    recent_sent timestamptz;
    media_kind text := nullif(p_media_type,'');
begin
    if actor_id is null then raise exception 'Authentication required'; end if;
    if char_length(clean_body)>500 then return jsonb_build_object('success',false,'code','MESSAGE_TOO_LONG','limit',500); end if;
    if char_length(btrim(clean_body))=0 and p_media_url is null then
        return jsonb_build_object('success',false,'code','EMPTY_MESSAGE');
    end if;
    if media_kind is not null and media_kind not in ('image','gif') then
        return jsonb_build_object('success',false,'code','INVALID_MEDIA_TYPE');
    end if;
    if p_media_url is not null and (
        p_media_url !~ '^https://[^[:space:]]+$'
        or p_media_url !~ '^https://[^/]+/storage/v1/object/public/worth-it-chat-media/'
    ) then return jsonb_build_object('success',false,'code','INVALID_MEDIA_URL'); end if;

    select conversation_type into target_type from public.worth_it_chat_conversations where id=target_id;
    if target_type is null then return jsonb_build_object('success',false,'code','CHAT_NOT_FOUND'); end if;
    if target_type <> 'global' and not exists (
        select 1 from public.worth_it_chat_members where conversation_id=target_id and user_id=actor_id
    ) then return jsonb_build_object('success',false,'code','NOT_A_CHAT_MEMBER'); end if;

    if target_type='direct' and not exists (
        select 1 from public.worth_it_chat_members a
        join public.worth_it_chat_members b on b.conversation_id=a.conversation_id and b.user_id<>a.user_id
        join public.worth_it_friends f on
            (f.user_low_id=a.user_id and f.user_high_id=b.user_id) or
            (f.user_low_id=b.user_id and f.user_high_id=a.user_id)
        where a.conversation_id=target_id and a.user_id=actor_id
    ) then return jsonb_build_object('success',false,'code','FRIENDS_ONLY'); end if;

    perform pg_advisory_xact_lock(hashtextextended('worth-it-chat:'||actor_id::text,0));
    select max(created_at) into recent_sent from public.worth_it_chat_messages
    where sender_user_id=actor_id;
    if recent_sent is not null and recent_sent > now()-interval '2 seconds' then
        return jsonb_build_object('success',false,'code','CHAT_COOLDOWN',
            'retry_after_ms',greatest(1,ceil(extract(epoch from (recent_sent+interval '2 seconds'-now()))*1000)));
    end if;

    masked_body:=clean_body;
    if masked_body ~ '(ε⥰|\\(‿ˠ‿\\)|Ɑ͞|لں͞|⎛₎╰\\(☫\\)╯₍⎞)' then
        masked_body:=regexp_replace(masked_body,'(ε⥰|\\(‿ˠ‿\\)|Ɑ͞|لں͞|⎛₎╰\\(☫\\)╯₍⎞)','***','gi');
        filter_reason:= 'Glitch-style or potentially harmful symbols were filtered.';
    end if;
    if masked_body ~ '[卐卍☫]' then
        masked_body:=regexp_replace(masked_body,'[卐卍☫]','*','g');
        filter_reason:= 'Hate symbols or potentially harmful imagery were filtered.';
    end if;
    if masked_body ~ U&'[\0300-\036F\0483-\0489\0591-\05BD\0610-\061A\064B-\065F\1AB0-\1AFF\1DC0-\1DFF\20D0-\20FF\FE20-\FE2F]' then
        masked_body:=regexp_replace(masked_body,U&'[\0300-\036F\0483-\0489\0591-\05BD\0610-\061A\064B-\065F\1AB0-\1AFF\1DC0-\1DFF\20D0-\20FF\FE20-\FE2F]','*','g');
        filter_reason:=coalesce(filter_reason||' ', '') || 'Glitch/combining Unicode characters were filtered.';
    end if;
    for term_row in select term,reason from public.worth_it_chat_filter_terms where enabled order by char_length(term) desc loop
        if masked_body ~* ('(^|[^[:alnum:]_])'||term_row.term||'([^[:alnum:]_]|$)') then
            masked_body:=regexp_replace(masked_body,
                '(^|[^[:alnum:]_])('||term_row.term||')([^[:alnum:]_]|$)',
                E'\\1'||repeat('*',greatest(3,char_length(term_row.term)))||E'\\3','gi');
            filter_reason:=coalesce(filter_reason||' ', '')||term_row.reason||' was filtered.';
        end if;
    end loop;

    insert into public.worth_it_chat_messages(conversation_id,sender_user_id,body,media_url,media_type,filtered_reason)
    values(target_id,actor_id,masked_body,nullif(p_media_url,''),media_kind,filter_reason)
    returning id into message_id;
    return jsonb_build_object('success',true,'message_id',message_id,'filtered',filter_reason is not null,
        'filtered_reason',filter_reason,'body',masked_body);
end; $$;

create or replace function public.get_worth_it_chat_notification_preferences()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    actor_id uuid := auth.uid();
    result jsonb;
begin
    if actor_id is null then
        raise exception 'Authentication required';
    end if;

    select coalesce(jsonb_object_agg(chat_key, notifications_enabled), '{}'::jsonb)
      into result
      from public.worth_it_chat_notification_preferences
     where user_id = actor_id;

    return result;
end;
$$;

create or replace function public.set_worth_it_chat_notifications(
    p_chat_key text,
    p_enabled boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    actor_id uuid := auth.uid();
    target_worth_it_id bigint;
    target_user_id uuid;
    target_conversation_id uuid;
begin
    if actor_id is null then
        raise exception 'Authentication required';
    end if;

    if p_chat_key is null or p_enabled is null then
        return jsonb_build_object('success', false, 'code', 'INVALID_NOTIFICATION_SETTING');
    end if;

    if p_chat_key = 'global' then
        null;
    elsif p_chat_key ~ '^direct:[1-9][0-9]*$' then
        begin
            target_worth_it_id := substring(p_chat_key from 8)::bigint;
        exception when others then
            return jsonb_build_object('success', false, 'code', 'INVALID_CHAT');
        end;

        select p.user_id
          into target_user_id
          from public.worth_it_profiles p
         where p.worth_it_id = target_worth_it_id;

        if target_user_id is null or target_user_id = actor_id or not exists (
            select 1
              from public.worth_it_friends f
             where (f.user_low_id = actor_id and f.user_high_id = target_user_id)
                or (f.user_low_id = target_user_id and f.user_high_id = actor_id)
        ) then
            return jsonb_build_object('success', false, 'code', 'FRIENDS_ONLY');
        end if;
    elsif p_chat_key ~ '^group:[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$' then
        begin
            target_conversation_id := substring(p_chat_key from 7)::uuid;
        exception when others then
            return jsonb_build_object('success', false, 'code', 'INVALID_CHAT');
        end;

        if not exists (
            select 1
              from public.worth_it_chat_conversations c
              join public.worth_it_chat_members m on m.conversation_id = c.id
             where c.id = target_conversation_id
               and c.conversation_type = 'group'
               and m.user_id = actor_id
        ) then
            return jsonb_build_object('success', false, 'code', 'NOT_A_CHAT_MEMBER');
        end if;
    else
        return jsonb_build_object('success', false, 'code', 'INVALID_CHAT');
    end if;

    insert into public.worth_it_chat_notification_preferences
        (user_id, chat_key, notifications_enabled, updated_at)
    values (actor_id, p_chat_key, p_enabled, now())
    on conflict (user_id, chat_key)
    do update set notifications_enabled = excluded.notifications_enabled,
                  updated_at = now();

    return jsonb_build_object(
        'success', true,
        'chat_key', p_chat_key,
        'notifications_enabled', p_enabled
    );
end;
$$;

