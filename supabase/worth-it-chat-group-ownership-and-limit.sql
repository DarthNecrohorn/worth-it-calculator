-- Worth It group ownership succession and 10-group membership cap.
-- Apply only after preview validation; this file is not a production migration action.
begin;

-- Stable per-group join order. Existing memberships receive a sequence value;
-- future joins and invited members receive values in insertion order.
alter table public.worth_it_chat_members
  add column if not exists member_order bigint generated by default as identity;

-- Normalize legacy rows: the current Owner is first, then preserve join timestamps
-- and use user id only as a deterministic tie-breaker for old equal timestamps.
with ordered_members as (
  select cm.conversation_id, cm.user_id,
         row_number() over (
           partition by cm.conversation_id
           order by (cm.user_id = c.created_by) desc, cm.joined_at asc, cm.user_id asc
         ) as desired_order
    from public.worth_it_chat_members cm
    join public.worth_it_chat_conversations c on c.id = cm.conversation_id
   where c.conversation_type = 'group'
)
update public.worth_it_chat_members cm
   set member_order = ordered_members.desired_order
  from ordered_members
 where cm.conversation_id = ordered_members.conversation_id
   and cm.user_id = ordered_members.user_id;

create unique index if not exists worth_it_chat_members_member_order_idx
  on public.worth_it_chat_members(conversation_id, member_order);

create or replace function public.leave_worth_it_group_chat(p_conversation_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_id uuid := auth.uid();
  group_owner uuid;
  next_owner uuid;
  member_count integer;
begin
  if actor_id is null then raise exception 'Authentication required'; end if;

  select c.created_by into group_owner
    from public.worth_it_chat_conversations c
   where c.id = p_conversation_id and c.conversation_type = 'group'
   for update;
  if not found then return jsonb_build_object('success', false, 'code', 'GROUP_NOT_FOUND'); end if;

  perform pg_advisory_xact_lock(hashtextextended('worth-it-group-membership:' || actor_id::text, 0));
  if not exists (
    select 1 from public.worth_it_chat_members
     where conversation_id = p_conversation_id and user_id = actor_id
  ) then return jsonb_build_object('success', false, 'code', 'NOT_A_GROUP_MEMBER'); end if;

  select count(*)::integer into member_count
    from public.worth_it_chat_members where conversation_id = p_conversation_id;

  if member_count <= 1 then
    delete from public.worth_it_chat_conversations where id = p_conversation_id;
    return jsonb_build_object('success', true, 'group_deleted', true, 'owner_transferred', false);
  end if;

  if group_owner = actor_id then
    select user_id into next_owner
      from public.worth_it_chat_members
     where conversation_id = p_conversation_id and user_id <> actor_id
     order by member_order asc, joined_at asc, user_id asc
     limit 1;
    if next_owner is null then
      delete from public.worth_it_chat_conversations where id = p_conversation_id;
      return jsonb_build_object('success', true, 'group_deleted', true, 'owner_transferred', false);
    end if;
    update public.worth_it_chat_conversations
       set created_by = next_owner
     where id = p_conversation_id;
  end if;

  delete from public.worth_it_chat_members
   where conversation_id = p_conversation_id and user_id = actor_id;

  return jsonb_build_object(
    'success', true, 'group_deleted', false,
    'owner_transferred', group_owner = actor_id,
    'new_owner_user_id', case when group_owner = actor_id then next_owner else null end
  );
end;
$$;

create or replace function public.create_worth_it_group_chat(
  p_title text,
  p_member_worth_it_ids bigint[]
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_id uuid := auth.uid();
  conversation uuid;
  member_id bigint;
  member_user uuid;
  candidate_ids uuid[];
  locked_user uuid;
  clean_title text := nullif(btrim(coalesce(p_title, '')), '');
  requested_count integer := coalesce(cardinality(p_member_worth_it_ids), 0);
  generated_invite_token text := lower(replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''));
  group_count integer;
begin
  if actor_id is null then raise exception 'Authentication required'; end if;
  if clean_title is null or char_length(clean_title) > 60 then
    return jsonb_build_object('success', false, 'code', 'INVALID_GROUP_TITLE');
  end if;
  if requested_count < 2 or requested_count > 29 then
    return jsonb_build_object('success', false, 'code', 'INVALID_GROUP_SIZE', 'max_members', 30);
  end if;
  if (select count(distinct x) from unnest(p_member_worth_it_ids) x) <> requested_count then
    return jsonb_build_object('success', false, 'code', 'DUPLICATE_GROUP_MEMBER');
  end if;

  -- Resolve every invitee first, then take per-user locks in deterministic order
  -- so simultaneous group creations/joins cannot exceed the per-user cap.
  select array_agg(user_id order by user_id) into candidate_ids
    from (
      select actor_id as user_id
      union
      select p.user_id
        from unnest(p_member_worth_it_ids) wanted(id)
        join public.worth_it_profiles p on p.worth_it_id = wanted.id
    ) resolved;
  if coalesce(cardinality(candidate_ids), 0) <> requested_count + 1 then
    return jsonb_build_object('success', false, 'code', 'INVALID_GROUP_PARTICIPANT');
  end if;

  foreach locked_user in array candidate_ids loop
    perform pg_advisory_xact_lock(hashtextextended('worth-it-group-membership:' || locked_user::text, 0));
  end loop;

  foreach member_id in array p_member_worth_it_ids loop
    select user_id into member_user
      from public.worth_it_profiles where worth_it_id = member_id;
    if member_user is null or member_user = actor_id then
      return jsonb_build_object('success', false, 'code', 'INVALID_GROUP_PARTICIPANT');
    end if;
    if not exists (
      select 1 from public.worth_it_friends
       where (user_low_id = actor_id and user_high_id = member_user)
          or (user_low_id = member_user and user_high_id = actor_id)
    ) then
      return jsonb_build_object('success', false, 'code', 'GROUP_PARTICIPANTS_MUST_BE_FRIENDS');
    end if;
  end loop;

  if exists (
    select 1 from unnest(candidate_ids) u(user_id)
     where (select count(*) from public.worth_it_chat_members cm
            join public.worth_it_chat_conversations c on c.id = cm.conversation_id
            where cm.user_id = u.user_id and c.conversation_type = 'group') >= 10
  ) then
    return jsonb_build_object('success', false, 'code', 'GROUP_LIMIT_REACHED', 'max_groups', 10);
  end if;

  insert into public.worth_it_chat_conversations(conversation_type, title, created_by, invite_token)
  values ('group', clean_title, actor_id, generated_invite_token)
  returning id into conversation;

  -- Insert creator first; identity member_order preserves creator/invite order.
  insert into public.worth_it_chat_members(conversation_id, user_id)
  values (conversation, actor_id);

  foreach member_id in array p_member_worth_it_ids loop
    select user_id into member_user
      from public.worth_it_profiles where worth_it_id = member_id;
    insert into public.worth_it_chat_members(conversation_id, user_id)
    values (conversation, member_user);
  end loop;

  return jsonb_build_object(
    'success', true, 'conversation_id', conversation,
    'invite_token', generated_invite_token, 'max_groups', 10
  );
end;
$$;

create or replace function public.accept_worth_it_group_invite(p_invite_token text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_id uuid := auth.uid();
  target_id uuid;
  target_title text;
  member_count integer;
  current_group_count integer;
begin
  if actor_id is null then raise exception 'Authentication required'; end if;
  if p_invite_token is null or lower(p_invite_token) !~ '^[0-9a-f]{64}$' then
    return jsonb_build_object('success', false, 'code', 'INVITE_NOT_FOUND');
  end if;

  select c.id, c.title into target_id, target_title
    from public.worth_it_chat_conversations c
   where c.conversation_type = 'group' and c.invite_token = lower(p_invite_token)
   for update;
  if target_id is null then return jsonb_build_object('success', false, 'code', 'INVITE_NOT_FOUND'); end if;

  perform pg_advisory_xact_lock(hashtextextended('worth-it-group-membership:' || actor_id::text, 0));
  if exists (
    select 1 from public.worth_it_chat_members
     where conversation_id = target_id and user_id = actor_id
  ) then
    return jsonb_build_object('success', true, 'already_member', true,
      'conversation_id', target_id, 'title', target_title, 'invite_token', lower(p_invite_token));
  end if;

  select count(*)::integer into current_group_count
    from public.worth_it_chat_members cm
    join public.worth_it_chat_conversations c on c.id = cm.conversation_id
   where cm.user_id = actor_id and c.conversation_type = 'group';
  if current_group_count >= 10 then
    return jsonb_build_object('success', false, 'code', 'GROUP_LIMIT_REACHED',
      'max_groups', 10, 'current_groups', current_group_count);
  end if;

  select count(*)::integer into member_count
    from public.worth_it_chat_members where conversation_id = target_id;
  if member_count >= 30 then
    return jsonb_build_object('success', false, 'code', 'GROUP_FULL', 'max_members', 30);
  end if;

  insert into public.worth_it_chat_members(conversation_id, user_id)
  values (target_id, actor_id);

  return jsonb_build_object('success', true, 'already_member', false,
    'conversation_id', target_id, 'title', target_title, 'invite_token', lower(p_invite_token),
    'current_groups', current_group_count + 1, 'max_groups', 10);
end;
$$;

create or replace function public.kick_worth_it_group_member(
  p_conversation_id uuid,
  p_target_worth_it_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_id uuid := auth.uid();
  group_owner uuid;
  target_user_id uuid;
begin
  if actor_id is null then raise exception 'Authentication required'; end if;
  select created_by into group_owner
    from public.worth_it_chat_conversations
   where id = p_conversation_id and conversation_type = 'group'
   for update;
  if not found then return jsonb_build_object('success', false, 'code', 'GROUP_NOT_FOUND'); end if;
  if group_owner is distinct from actor_id then
    return jsonb_build_object('success', false, 'code', 'NOT_GROUP_OWNER');
  end if;
  select user_id into target_user_id
    from public.worth_it_profiles where worth_it_id = p_target_worth_it_id;
  if target_user_id is null or target_user_id = actor_id then
    return jsonb_build_object('success', false, 'code', 'INVALID_GROUP_MEMBER');
  end if;
  if not exists (
    select 1 from public.worth_it_chat_members
     where conversation_id = p_conversation_id and user_id = target_user_id
  ) then
    return jsonb_build_object('success', false, 'code', 'NOT_A_GROUP_MEMBER');
  end if;

  perform pg_advisory_xact_lock(hashtextextended('worth-it-group-membership:' || target_user_id::text, 0));
  delete from public.worth_it_chat_members
   where conversation_id = p_conversation_id and user_id = target_user_id;
  return jsonb_build_object('success', true, 'kicked_worth_it_id', p_target_worth_it_id);
end;
$$;

revoke all on function public.leave_worth_it_group_chat(uuid) from public, anon;
revoke all on function public.create_worth_it_group_chat(text, bigint[]) from public, anon;
revoke all on function public.accept_worth_it_group_invite(text) from public, anon;
