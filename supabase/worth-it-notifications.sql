-- Worth It social notifications.
-- Run once in Supabase Dashboard -> SQL Editor after supabase/worth-it-social.sql.
-- Adds a notification inbox for unfriend events and an optional unfriend reason.

create table if not exists public.worth_it_social_notifications (
    id bigint generated by default as identity primary key,
    recipient_user_id uuid not null references auth.users(id) on delete cascade,
    actor_user_id uuid not null references auth.users(id) on delete cascade,
    notification_type text not null check (notification_type in ('unfriended')),
    reason text,
    created_at timestamptz not null default now(),
    read_at timestamptz,
    constraint worth_it_social_notifications_not_self check (recipient_user_id <> actor_user_id),
    constraint worth_it_social_notifications_reason_length check (reason is null or char_length(reason) <= 500)
);

create index if not exists worth_it_social_notifications_recipient_idx
    on public.worth_it_social_notifications(recipient_user_id, created_at desc);
create index if not exists worth_it_social_notifications_unread_idx
    on public.worth_it_social_notifications(recipient_user_id, created_at desc)
    where read_at is null;

alter table public.worth_it_social_notifications enable row level security;
revoke all on public.worth_it_social_notifications from anon, authenticated;

create or replace function public.get_worth_it_social_notifications()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    actor_id uuid := auth.uid();
    result jsonb;
begin
    if actor_id is null then
        raise exception 'Authentication required';
    end if;

    select coalesce(jsonb_agg(jsonb_build_object(
        'id', n.id,
        'type', n.notification_type,
        'reason', n.reason,
        'created_at', n.created_at,
        'read_at', n.read_at,
        'worth_it_id', p.worth_it_id,
        'username', p.username,
        'display_name', coalesce(p.display_name, p.username, 'Worth It member'),
        'avatar_url', p.avatar_url
    ) order by n.created_at desc), '[]'::jsonb)
    into result
    from public.worth_it_social_notifications n
    left join public.worth_it_profiles p on p.user_id = n.actor_user_id
    where n.recipient_user_id = actor_id;

    return result;
end;
$$;

create or replace function public.mark_worth_it_social_notifications_read()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
    actor_id uuid := auth.uid();
    updated_count integer := 0;
begin
    if actor_id is null then
        raise exception 'Authentication required';
    end if;

    update public.worth_it_social_notifications
    set read_at = now()
    where recipient_user_id = actor_id and read_at is null;

    get diagnostics updated_count = row_count;
    return updated_count;
end;
$$;

create or replace function public.unfriend_worth_it_user_with_reason(
    target_worth_it_id bigint,
    p_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    actor_id uuid := auth.uid();
    target_user_id uuid;
    low_id uuid;
    high_id uuid;
    trimmed_reason text := nullif(btrim(coalesce(p_reason, '')), '');
    deleted_count integer := 0;
begin
    if actor_id is null then
        raise exception 'Authentication required';
    end if;

    if p_reason is not null and char_length(p_reason) > 500 then
        return jsonb_build_object('success', false, 'code', 'INVALID_UNFRIEND_REASON',
            'error', 'The optional reason can contain up to 500 characters.');
    end if;

    select user_id into target_user_id
    from public.worth_it_profiles
    where worth_it_id = target_worth_it_id
    for update;

    if target_user_id is null then
        return jsonb_build_object('success', false, 'code', 'PROFILE_NOT_FOUND');
    end if;
    if target_user_id = actor_id then
        return jsonb_build_object('success', false, 'code', 'CANNOT_UNFRIEND_SELF');
    end if;

    low_id := least(actor_id, target_user_id);
    high_id := greatest(actor_id, target_user_id);

    delete from public.worth_it_friends
    where user_low_id = low_id and user_high_id = high_id;
    get diagnostics deleted_count = row_count;

    if deleted_count = 0 then
        return jsonb_build_object('success', false, 'code', 'NOT_FRIENDS',
            'error', 'You are no longer friends with this user.');
    end if;

    update public.worth_it_friend_requests
    set status = 'cancelled', updated_at = now()
    where user_low_id = low_id and user_high_id = high_id and status = 'accepted';

    insert into public.worth_it_social_notifications (
        recipient_user_id, actor_user_id, notification_type, reason
    ) values (
        target_user_id, actor_id, 'unfriended', trimmed_reason
    );

    return jsonb_build_object('success', true, 'are_friends', false, 'notification_created', true);
end;
$$;

-- Keep the existing no-reason RPC working for older clients, while also notifying the recipient.
create or replace function public.unfriend_worth_it_user(target_worth_it_id bigint)
returns jsonb
language sql
security definer
set search_path = public
as $$
    select public.unfriend_worth_it_user_with_reason(target_worth_it_id, null);
$$;

revoke all on function public.get_worth_it_social_notifications() from public, anon;
revoke all on function public.mark_worth_it_social_notifications_read() from public, anon;
revoke all on function public.unfriend_worth_it_user_with_reason(bigint, text) from public, anon;
revoke all on function public.unfriend_worth_it_user(bigint) from public, anon;

grant execute on function public.get_worth_it_social_notifications() to authenticated;
grant execute on function public.mark_worth_it_social_notifications_read() to authenticated;
grant execute on function public.unfriend_worth_it_user_with_reason(bigint, text) to authenticated;
grant execute on function public.unfriend_worth_it_user(bigint) to authenticated;
