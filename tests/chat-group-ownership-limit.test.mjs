import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const read = path => readFileSync(new URL("../" + path, import.meta.url), "utf8");
const sql = read("supabase/worth-it-chat-group-ownership-and-limit.sql");
const chat = read("chat-ui.js");
const html = read("index.html");

test("group owner succession follows persisted membership join order", () => {
  assert.match(sql, /member_order bigint generated by default as identity/);
  assert.match(sql, /order by member_order asc, joined_at asc, user_id asc/);
  assert.match(sql, /set created_by = next_owner/);
  assert.match(sql, /owner_transferred/);
});

test("the 10-group cap is enforced for group creation and invite acceptance", () => {
  assert.match(sql, /GROUP_LIMIT_REACHED/);
  assert.match(sql, />= 10/);
  assert.match(sql, /worth-it-group-membership:/);
  assert.match(sql, /create or replace function public\.create_worth_it_group_chat/);
  assert.match(sql, /create or replace function public\.accept_worth_it_group_invite/);
  assert.match(chat, /maximum of 10 groups/);
  assert.match(chat, /already in 10 groups/);
});

test("only the current group Owner can kick members, enforced by the database", () => {
  assert.match(sql, /create or replace function public\.kick_worth_it_group_member/);
  assert.match(sql, /group_owner is distinct from actor_id/);
  assert.match(sql, /NOT_GROUP_OWNER/);
  assert.match(sql, /delete from public\.worth_it_chat_members[\s\S]*?target_user_id/);
  assert.match(html, /id="worthItChatGroupMembersList"/);
  assert.match(chat, /worth-it-chat-group-member-kick/);
  assert.match(chat, /rpcName = action === "delete" \? "delete_worth_it_group_chat" : action === "kick" \? "kick_worth_it_group_member"/);
  assert.match(chat, /conversation\.is_creator !== true/);
});

test("leaving removes the membership and therefore removes the group from the member's group list", () => {
  assert.match(sql, /delete from public\.worth_it_chat_members[\s\S]*?user_id = actor_id/);
  assert.match(sql, /owner_transferred/);
});

test("mobile chat header separates direct identity, global chat, and group roster", () => {
  assert.match(chat, /is-global-chat/);
  assert.match(chat, /is-group-members-trigger/);
  assert.match(chat, /openWorthItGroupMembers/);
  assert.match(chat, /worthItChatGroupMembersList/);
  assert.match(html, /<button[^>]*id="worthItChatHeaderAvatar"/);
});

test("the site navigation is hidden without hiding its nested chat overlay", () => {
  const css = read("style.css");
  const html = read("index.html");
  assert.ok(css.includes("body.worth-it-chat-open > nav.nav { visibility:hidden !important; pointer-events:none !important; }"));
  assert.ok(css.includes("body.worth-it-chat-open > nav.nav #worthItChatOverlay:not([hidden]) { visibility:visible !important; pointer-events:auto !important; }"));
  assert.match(html, /<div class="worth-it-chat-overlay" id="worthItChatOverlay" hidden/);
  assert.match(css, /\.worth-it-chat-overlay\[hidden\][^{]*\{display:none!important\}/);
});
